// Shared ko/en dictionary for the five operator consoles
// (admin / partner / developer / creator / ads). Internal tools ship with
// Korean + English; the user messenger keeps its own 4-locale dictionary.
// Every key must exist in both locales (see scripts/console_i18n.test.mjs).
export type ConsoleLocale = 'ko' | 'en'

export function detectConsoleLocale(): ConsoleLocale {
  try {
    const saved = localStorage.getItem('luno.console.locale')
    if (saved === 'ko' || saved === 'en') return saved
  } catch { /* non-browser */ }
  if (typeof navigator !== 'undefined' && (navigator.language || '').toLowerCase().startsWith('en')) return 'en'
  return 'ko'
}

export function setConsoleLocale(locale: ConsoleLocale): void {
  try { localStorage.setItem('luno.console.locale', locale) } catch { /* non-browser */ }
}

export function consoleT(locale: ConsoleLocale, key: string, params?: Record<string, string | number>): string {
  let s: string = CONSOLE_DICT[locale]?.[key] ?? CONSOLE_DICT.en[key] ?? key
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, String(v))
  }
  return s
}

